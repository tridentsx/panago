// MainListHeader is the header for the MAIN partition's sub-entry list
type MainListHeader struct {
	Checksum      uint32 // List checksum: Adler32(listHeader[4:ListSize])
	FormatVersion uint32 // Always 1; list format version
	ListSize      uint32 // Total size of list including this header
	DecompSize    uint32 // Decompressed chunk size per entry (observed: 0x1000000 = 16MB)
	CompType      uint32 // Compression type: 0=uncompressed (ByteSum check), 2=LZSS (per-entry Adler32 check)
}

// MainListEntry represents an entry in the MAIN partition list
type MainListEntry struct {
	Size     uint32 // Entry size
	Checksum uint32 // Entry checksum
}

// MainEntryHeader is the 64-byte header for each sub-entry in MAIN
type MainEntryHeader struct {
	Signature    [14]byte // Entry signature (e.g. "EXTRHEADDRVD  ")
	CompType     uint16   // Compression type (observed: 2 = raw LZSS)
	DecompSize   uint32   // Decompressed size
	DestAddr     uint32   // Destination address in memory
	CompSize     uint32   // Compressed size
	Slack        uint32   // BufferConstant - FooterOffset (unused space in allocation)
	FooterOffset uint32   // 64 + align4(CompSize) — offset of footer within entry
	BaseAddr     uint32   // Base address (observed: 0)
	Checksum     uint32   // Adler32 of every 16th byte of decompressed data
	ChecksumFlag uint8    // Checksum flag (observed: 0x10)
	Unused       [19]byte // Padding
}

// MainPartitionMetadata stores structural parameters for the MAIN partition.
// Most per-entry fields (FooterOff, ListSize) are computed from CompSize during
// encoding. Only values that can't be derived are stored here.
type MainPartitionMetadata struct {
	FirstHeader        string `json:"first_header"`        // Hex-encoded 0x30-byte first header (payload size, "PANASONIC", build timestamp)
	FormatVersion      uint32 `json:"format_version"`      // MainListHeader.FormatVersion (always 1)
	ListHeaderCompType uint32 `json:"list_header_comp_type"` // MainListHeader.CompType: 0=uncompressed, 2=LZSS
	EntrySignature string `json:"entry_signature"`  // Hex-encoded 14-byte entry signature
	CompType       uint16 `json:"comp_type"`        // Compression type for all entries (observed: 2)
	ChunkSize      uint32 `json:"chunk_size"`       // Decompressed chunk size for full chunks (observed: 0x1000000 = 16MB)
	// BufferConstant is NOT uniform across entries — it scales with each
	// entry's own decompressed size (confirmed against real firmware: the
	// last, smaller-than-chunkSize entry uses a proportionally smaller
	// BufferConstant than the full-size entries). Captured per-entry, paired
	// with DecompSizes, so re-encoding can look up the right BufferConstant
	// by actual decompressed size rather than assuming entry i always means
	// the same thing (which breaks the moment modified content needs a
	// different number/size of chunks than the original).
	BufferConstants []uint32 `json:"buffer_constants"`
	DecompSizes     []uint32 `json:"decomp_sizes"` // DecompSizes[i] is entry i's real decompressed size
	ChecksumFlag    uint8    `json:"checksum_flag"` // Entry header checksum flag (observed: 0x10)
	EntryCount      int      `json:"entry_count"`   // Number of sub-entries
}

// FirmwareInfo contains metadata about a firmware file
type FirmwareInfo struct {
	TotalSize  int64
	Partitions []PartitionInfo
}

// PartitionInfo contains metadata about a partition
type PartitionInfo struct {
	Name     string
	Version  string
	Offset   uint32
	Size     uint32
	Checksum uint32
}

