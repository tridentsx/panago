package cramfs

// Superblock represents the header of a Cramfs filesystem
// Added block alignment and padding for proper struct alignment
type Superblock struct {
	Magic     uint32   // Magic number (0x28cd3d45)
	Size      uint32   // Filesystem size in bytes
	Flags     uint32   // Filesystem flags
	Future    uint32   // Reserved for future use
	Signature [16]byte // "Compressed ROMFS"
	FSCRC     uint32   // CRC checksum
	Edition   uint32   // Filesystem edition
	Blocks    uint32   // Number of blocks
	Files     uint32   // Number of files
	Name      [16]byte // Filesystem name
}

type Inode struct {
	Mode    uint16 // File mode (directory, symlink, file, etc.)
	UID     uint16 // User ID
	Size    uint32 // File size in bytes
	GID     uint16 // Group ID
	Namelen uint16 // Length of filename
	Offset  uint32 // Data block offset
}

