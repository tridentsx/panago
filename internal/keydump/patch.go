package keydump

import (
	"fmt"
	"os"
)

const (
	BASE           = 0x29f00000
	PATCH_AREA     = 0x76d6
	KEY_INIT_FUNC  = 0x55dc
)

// PatchLibrary patches libfmupre.so to dump FPC keys
func PatchLibrary(inputPath, outputPath string) error {
	data, err := os.ReadFile(inputPath)
	if err != nil {
		return fmt.Errorf("failed to read input: %w", err)
	}

	patched := make([]byte, len(data))
	copy(patched, data)

	// Hook code (Thumb-2 assembly)
	hook := []byte{
		// push {r4-r7, lr}
		0x2d, 0xe9, 0xf0, 0x40,
		// mov r4, r0 / mov r5, r1 / mov r6, r2
		0x04, 0x46, 0x0d, 0x46, 0x16, 0x46,
		// ldr r0, [pc, #64] @ filename
		0x10, 0x48,
		// movw r1, #0x241 (O_WRONLY|O_CREAT|O_TRUNC)
		0x40, 0xf2, 0x41, 0x21,
		// movw r2, #0x1a4 (0644)
		0x40, 0xf2, 0xa4, 0x12,
		// mov r7, #5 (SYS_open) / svc 0
		0x05, 0x27, 0x00, 0xdf,
		// cmp r0, #0 / blt skip
		0x00, 0x28, 0x11, 0xdb,
		// mov r7, r0 (save fd)
		0x07, 0x46,
		// write(fd, key1, 8)
		0x21, 0x46, 0x08, 0x22, 0x80, 0xb4, 0x04, 0x27, 0x00, 0xdf, 0x80, 0xbc,
		// write(fd, key2, 8)
		0x38, 0x46, 0x29, 0x46, 0x08, 0x22, 0x80, 0xb4, 0x04, 0x27, 0x00, 0xdf, 0x80, 0xbc,
		// close(fd)
		0x38, 0x46, 0x06, 0x27, 0x00, 0xdf,
		// restore: mov r0, r4 / mov r1, r5 / mov r2, r6
		0x20, 0x46, 0x29, 0x46, 0x32, 0x46,
		// pop {r4-r7, lr}
		0xbd, 0xe8, 0xf0, 0x40,
		// b.w to 0x55e0 (original + 4)
		0xfd, 0xf7, 0x5f, 0xbf,
		// padding
		0x00, 0x00,
	}

	// Filename (4-byte aligned)
	filename := []byte("/tmp/fpc_keys.bin\x00\x00\x00")

	// Install hook at padding area
	copy(patched[PATCH_AREA:], hook)
	copy(patched[PATCH_AREA+len(hook):], filename)

	// Patch entry point: b.w PATCH_AREA
	// offset = 0x76d6 - 0x55e0 = 0x20f6
	patched[KEY_INIT_FUNC] = 0x02
	patched[KEY_INIT_FUNC+1] = 0xf0
	patched[KEY_INIT_FUNC+2] = 0x7b
	patched[KEY_INIT_FUNC+3] = 0xb8

	if err := os.WriteFile(outputPath, patched, 0755); err != nil {
		return fmt.Errorf("failed to write output: %w", err)
	}

	return nil
}

// EmbeddedPatch returns the binary patch data that can be applied to libfmupre.so
// This allows patching without needing the original library file
func EmbeddedPatch() []PatchEntry {
	return []PatchEntry{
		// Entry point redirect
		{Offset: KEY_INIT_FUNC, Data: []byte{0x02, 0xf0, 0x7b, 0xb8}},
		// Hook code
		{Offset: PATCH_AREA, Data: []byte{
			0x2d, 0xe9, 0xf0, 0x40, 0x04, 0x46, 0x0d, 0x46, 0x16, 0x46, 0x10, 0x48,
			0x40, 0xf2, 0x41, 0x21, 0x40, 0xf2, 0xa4, 0x12, 0x05, 0x27, 0x00, 0xdf,
			0x00, 0x28, 0x11, 0xdb, 0x07, 0x46, 0x21, 0x46, 0x08, 0x22, 0x80, 0xb4,
			0x04, 0x27, 0x00, 0xdf, 0x80, 0xbc, 0x38, 0x46, 0x29, 0x46, 0x08, 0x22,
			0x80, 0xb4, 0x04, 0x27, 0x00, 0xdf, 0x80, 0xbc, 0x38, 0x46, 0x06, 0x27,
			0x00, 0xdf, 0x20, 0x46, 0x29, 0x46, 0x32, 0x46, 0xbd, 0xe8, 0xf0, 0x40,
			0xfd, 0xf7, 0x5f, 0xbf, 0x00, 0x00,
			// filename
			0x2f, 0x74, 0x6d, 0x70, 0x2f, 0x66, 0x70, 0x63, 0x5f, 0x6b, 0x65, 0x79,
			0x73, 0x2e, 0x62, 0x69, 0x6e, 0x00, 0x00, 0x00,
		}},
	}
}

// PatchEntry represents a single patch to apply
type PatchEntry struct {
	Offset int
	Data   []byte
}

// ApplyPatches applies patches to binary data
func ApplyPatches(data []byte, patches []PatchEntry) []byte {
	result := make([]byte, len(data))
	copy(result, data)
	for _, p := range patches {
		copy(result[p.Offset:], p.Data)
	}
	return result
}
